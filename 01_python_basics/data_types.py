
# Python Fundamentals - Ders 03
# Temel veri turleri

# 1. Metin (str)
isim = "Sudenur"

# 2. Tam sayi (int)
ders_sayisi = 5

# 3. Ondalikli sayi (float)
fiyat = 149.90

# 4. Mantiksal deger (bool)
aktif_mi = True

# Degerleri ekrana yazdiralim
print(isim)
print(ders_sayisi)
print(fiyat)
print(aktif_mi)

# Veri turlerini kontrol edelim
print(type(isim))
print(type(ders_sayisi))
print(type(fiyat))
print(type(aktif_mi))

# Cikti

